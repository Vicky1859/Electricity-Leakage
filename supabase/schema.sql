create table if not exists public.readings (
  id bigint generated by default as identity primary key,
  device_id text not null default 'room-1',
  room text not null default 'Main Room',
  current_a double precision,
  voltage_v double precision,
  temperature_c double precision,
  power_w double precision,
  occupied boolean,
  appliance_on boolean,
  buzzer_on boolean,
  led_on boolean,
  created_at timestamptz not null default now()
);

create index if not exists readings_created_at_idx on public.readings (created_at desc);
create index if not exists readings_device_id_idx on public.readings (device_id);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  device_id text not null default 'room-1',
  event_type text not null,
  message text not null,
  severity text not null default 'info',
  resolved boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists events_created_at_idx on public.events (created_at desc);

create table if not exists public.commands (
  id bigint generated by default as identity primary key,
  device_id text not null default 'room-1',
  command text not null,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  completed_at timestamptz
);

-- Keep direct browser access disabled. The server uses the private service-role key.
alter table public.readings enable row level security;
alter table public.events enable row level security;
alter table public.commands enable row level security;
